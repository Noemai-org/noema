package lincheck

import (
	"fmt"
	"math/rand"
	"testing"
)

// A register with write(v) and read() -> v, and an increment-and-get counter, as sequential specifications.
type regIn struct {
	write bool
	v     int
}

var register = Model{
	Init: func() any { return 0 },
	Step: func(state, in, out any, pending bool) (any, bool) {
		i := in.(regIn)
		if i.write {
			return i.v, true
		}
		if pending {
			return state, true
		}
		return state, out.(int) == state.(int)
	},
	Key: func(s any) string { return fmt.Sprint(s) },
}

var counter = Model{
	Init: func() any { return 0 },
	Step: func(state, in, out any, pending bool) (any, bool) {
		next := state.(int) + 1
		if pending {
			return next, true
		}
		return next, out.(int) == next
	},
	Key: func(s any) string { return fmt.Sprint(s) },
}

func op(client int, in, out any, call, ret int64) Operation {
	return Operation{ClientID: client, Input: in, Output: out, Call: call, Return: ret}
}

func pend(client int, in any, call int64) Operation {
	return Operation{ClientID: client, Input: in, Call: call, Pending: true}
}

func w(v int) regIn { return regIn{true, v} }

var r = regIn{false, 0}

func TestKnownRegisterHistories(t *testing.T) {
	cases := map[string]struct {
		h    []Operation
		want bool
	}{
		"sequential":                                      {[]Operation{op(1, w(1), nil, 1, 2), op(1, r, 1, 3, 4)}, true},
		"stale read after a completed write":              {[]Operation{op(1, w(1), nil, 1, 2), op(2, r, 0, 3, 4)}, false},
		"read during a write may see either":              {[]Operation{op(1, w(1), nil, 1, 4), op(2, r, 0, 2, 3), op(3, r, 1, 2, 3)}, true},
		"two reads cannot see 1 then 0":                   {[]Operation{op(1, w(1), nil, 1, 8), op(2, r, 1, 2, 3), op(2, r, 0, 4, 5)}, false},
		"pending write that took effect":                  {[]Operation{pend(1, w(1), 1), op(2, r, 1, 2, 3)}, true},
		"pending write that never happened":               {[]Operation{pend(1, w(1), 1), op(2, r, 0, 2, 3)}, true},
		"pending write cannot be undone":                  {[]Operation{pend(1, w(1), 1), op(2, r, 1, 2, 3), op(2, r, 0, 4, 5)}, false},
		"pending write cannot come before it was invoked": {[]Operation{op(2, r, 1, 1, 2), pend(1, w(1), 3)}, false},
		"value nobody wrote":                              {[]Operation{op(1, w(1), nil, 1, 2), op(2, r, 7, 3, 4)}, false},
		"empty":                                           {nil, true},
	}
	for name, tc := range cases {
		if got := Check(register, tc.h, 0); got.Linearizable != tc.want || got.Inconclusive {
			t.Errorf("%s: got %+v, want linearizable=%v", name, got, tc.want)
		}
	}
}

func TestLostUpdateIsCaught(t *testing.T) {
	// Two concurrent increments that both return 1: a lost update, not linearizable.
	lost := []Operation{op(1, "inc", 1, 1, 3), op(2, "inc", 1, 2, 4)}
	if Check(counter, lost, 0).Linearizable {
		t.Fatal("a lost update was accepted")
	}
	ok := []Operation{op(1, "inc", 1, 1, 3), op(2, "inc", 2, 2, 4)}
	if !Check(counter, ok, 0).Linearizable {
		t.Fatal("two increments returning 1 and 2 are linearizable")
	}
}

// Property: a history generated by actually running a sequential register at random linearization points is
// accepted; the same history with one read changed to a value nobody wrote is rejected. The checker can fail.
func TestRandomHistoriesBothWays(t *testing.T) {
	for seed := int64(1); seed <= 300; seed++ {
		rng := rand.New(rand.NewSource(seed))
		h := generate(rng, 3+rng.Intn(4), 4+rng.Intn(6))
		if got := Check(register, h, 0); !got.Linearizable || got.Inconclusive {
			t.Fatalf("seed %d: a history produced by a real register was rejected: %+v\n%v", seed, got, h)
		}
		if i := firstRead(h); i >= 0 {
			bad := append([]Operation(nil), h...)
			bad[i].Output = 1000 // never written
			if got := Check(register, bad, 0); got.Linearizable {
				t.Fatalf("seed %d: a read of a value nobody wrote was accepted", seed)
			}
		}
	}
}

func firstRead(h []Operation) int {
	for i, o := range h {
		if in := o.Input.(regIn); !in.write && !o.Pending {
			return i
		}
	}
	return -1
}

// generate runs `clients` concurrent clients against one register. Each operation takes effect at a random
// instant between its call and its return; some writes lose their response (pending).
func generate(rng *rand.Rand, clients, perClient int) []Operation {
	type ev struct {
		t      int64
		client int
		start  bool
	}
	var clock int64
	next := func() int64 { clock++; return clock }
	type pending struct {
		call   int64
		in     regIn
		effect bool
	}
	value := 0
	var h []Operation
	open := map[int]*pending{}
	remaining := make([]int, clients)
	for i := range remaining {
		remaining[i] = perClient
	}
	vcount := 0
	for {
		live := []int{}
		for c := 0; c < clients; c++ {
			if open[c] != nil || remaining[c] > 0 {
				live = append(live, c)
			}
		}
		if len(live) == 0 {
			return h
		}
		c := live[rng.Intn(len(live))]
		p := open[c]
		switch {
		case p == nil: // invoke
			vcount++
			in := regIn{write: rng.Intn(2) == 0, v: vcount}
			open[c] = &pending{call: next(), in: in}
			remaining[c]--
		case !p.effect: // take effect
			p.effect = true
			if p.in.write {
				value = p.in.v
			} else {
				p.in.v = value // remember what the read saw
			}
		default: // respond
			if p.in.write && rng.Intn(5) == 0 {
				h = append(h, Operation{ClientID: c, Input: regIn{true, p.in.v}, Call: p.call, Pending: true})
			} else {
				out := any(nil)
				if !p.in.write {
					out = p.in.v
				}
				h = append(h, Operation{ClientID: c, Input: regIn{p.in.write, p.in.v}, Output: out, Call: p.call, Return: next()})
			}
			open[c] = nil
		}
	}
}

func TestPartitionsAreCheckedIndependentlyAndTheFailingKeyIsNamed(t *testing.T) {
	h := []Operation{op(1, w(1), nil, 1, 2), op(1, r, 1, 3, 4), op(2, w(1), nil, 5, 6), op(2, r, 0, 7, 8)}
	key := func(o Operation) string {
		if o.Call < 5 {
			return "a"
		}
		return "b"
	}
	k, res := CheckPartitioned(register, h, key, 0)
	if k != "b" || res.Linearizable {
		t.Fatalf("key %q %+v", k, res)
	}
	if k, res := CheckPartitioned(register, h[:2], key, 0); k != "" || !res.Linearizable {
		t.Fatalf("%q %+v", k, res)
	}
}

func TestBudgetExhaustionIsInconclusiveNotAPass(t *testing.T) {
	var h []Operation
	for i := 0; i < 30; i++ { // 30 fully concurrent writes and an unsatisfiable read
		h = append(h, op(i, w(i+1), nil, int64(i+1), int64(100+i)))
	}
	h = append(h, op(99, r, 9999, 50, 200))
	got := Check(register, h, 50)
	if got.Linearizable || !got.Inconclusive {
		t.Fatalf("%+v", got)
	}
}
