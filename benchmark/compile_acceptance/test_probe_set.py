"""BEN-23 (A772): the 28 labelled phrasings as the offline probe set for the `requested_remedy` gate, and the B14 and B15 to B20 evidence in one table. For each phrasing: the boundary it was asked at (23 of the 28 are),
the gate recording that answers it and what replay does with that recording (SERVED, or EVIDENCE_ONLY for a reply the harness refuses as a whole). SYNTHETIC (AGENT-25). Seen failing first: no module."""
import json
import unittest
from pathlib import Path

from benchmark.compile_acceptance.probe_set import build, render
from benchmark.compile_acceptance.remedy_labelled import load

HERE = Path(__file__).resolve().parent
COMMITTED = HERE / "boundary-a604" / "probe-set.v1.json"
SET = HERE / "remedy_labelled.v1.json"


class ProbeSet(unittest.TestCase):
    def setUp(self) -> None:
        self.doc = build()

    def test_all_twenty_eight_labelled_phrasings_are_in_the_set_in_order_with_their_text(self) -> None:
        labelled = load(SET)
        self.assertEqual([i["item_id"] for i in self.doc["items"]], [i.item_id for i in labelled])
        self.assertEqual([i["text"] for i in self.doc["items"]], [i.text for i in labelled])
        self.assertEqual(len(self.doc["items"]), 28)

    def test_twenty_three_are_asked_at_a_boundary_and_five_have_no_recording(self) -> None:
        asked = [i for i in self.doc["items"] if i["boundary"] is not None]
        self.assertEqual(len(asked), 23)
        for item in self.doc["items"]:
            if item["boundary"] is None:
                self.assertEqual((item["replay"], item["gate_recording"]), ("NO_RECORDING", None), item["item_id"])

    def test_replay_serves_every_asked_boundary_but_the_malformed_five_and_the_three_not_committed(self) -> None:
        for item in self.doc["items"]:
            if item["boundary"] in ("B16", "B17", "B18", "B19", "B20"):
                self.assertEqual(item["replay"], "EVIDENCE_ONLY", item["boundary"])
            elif item["boundary"] in ("B02", "B06", "B12"):
                self.assertEqual(item["replay"], "NOT_COMMITTED", item["boundary"])  # their text holds a digit run of five or more: generated by a test, never committed
            elif item["boundary"] is not None:
                self.assertEqual(item["replay"], "SERVED", item["boundary"])

    def test_the_evidence_table_has_b14_and_b15_to_b20_with_the_gate_outcome_and_the_replay_label(self) -> None:
        rows = {r["boundary"]: r for r in self.doc["evidence"]}
        self.assertEqual(list(rows), ["B14", "B15", "B16", "B17", "B18", "B19", "B20"])
        self.assertEqual(rows["B14"]["gate_outcome"], "ABSENT")  # A649: an exponent form is malformed and the slot abstains
        self.assertEqual(rows["B14"]["replay"], "SERVED")
        for b in ("B15", "B16", "B17", "B18", "B19", "B20"):
            self.assertEqual(rows[b]["gate_outcome"], "ABSENT", b)
        for b in ("B16", "B17", "B18", "B19", "B20"):
            self.assertEqual(rows[b]["replay"], "EVIDENCE_ONLY", b)

    def test_the_committed_copy_is_not_stale_and_says_synthetic(self) -> None:
        self.assertEqual(COMMITTED.read_text(encoding="utf-8"), render(self.doc))
        self.assertTrue(json.loads(COMMITTED.read_text(encoding="utf-8"))["label"].startswith("SYNTHETIC"))


if __name__ == "__main__":
    unittest.main()
