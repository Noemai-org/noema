#!/usr/bin/env python3
"""Regenerate the hash-pinned lock files of a Python service (dependency pinning, PLT-02).

Usage: python3 -I tools/lock_python.py services/model

Reads [project] dependencies and [project.optional-dependencies] dev from pyproject.toml (every
direct dependency is pinned with ==), installs them into a throwaway virtual environment, freezes
the resolved set and writes requirements.lock (runtime) and requirements-dev.lock (runtime plus
dev) with every published file hash of each pinned version from the PyPI JSON API. Install with:

    pip install --require-hashes -r requirements.lock

Standard library only (plus the pip of the interpreter that runs it). A check, not production code.
"""
import json
import subprocess
import sys
import tempfile
import tomllib
import urllib.request
from pathlib import Path


def freeze(deps: list[str]) -> list[tuple[str, str]]:
    with tempfile.TemporaryDirectory() as tmp:
        venv = Path(tmp) / "v"
        subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
        py = str(venv / "bin" / "python")
        subprocess.run([py, "-m", "pip", "install", "-q", *deps], check=True)
        out = subprocess.run([py, "-m", "pip", "freeze"], check=True, capture_output=True, text=True).stdout
    pairs = []
    for line in out.splitlines():
        name, _, version = line.partition("==")
        if version:
            pairs.append((name, version))
    return sorted(pairs, key=lambda p: p[0].lower())


def hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as resp:
        data = json.load(resp)
    return sorted({f["digests"]["sha256"] for f in data["urls"]})


def write(path: Path, pairs: list[tuple[str, str]], header: str) -> None:
    lines = [header]
    for name, version in pairs:
        hs = hashes(name, version)
        lines.append(f"{name}=={version} \\")
        lines.append(" \\\n".join(f"    --hash=sha256:{h}" for h in hs))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(service: str) -> int:
    root = Path(service)
    project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    runtime = project["dependencies"]
    dev = project.get("optional-dependencies", {}).get("dev", [])
    for dep in runtime + dev:
        if "==" not in dep:
            sys.exit(f"{dep}: every direct dependency must be pinned with ==")
    hdr = "# Generated by tools/lock_python.py from pyproject.toml. Do not edit by hand. Install with --require-hashes."
    write(root / "requirements.lock", freeze(runtime), hdr + " Runtime set.")
    write(root / "requirements-dev.lock", freeze(runtime + dev), hdr + " Runtime plus dev set.")
    print(f"wrote {root}/requirements.lock and {root}/requirements-dev.lock")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
