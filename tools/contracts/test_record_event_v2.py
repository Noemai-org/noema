"""record-event.v2 and reconstruction.v2 (DEC-2026-10-27-record-event-v2): what JSON Schema cannot state, checked over the fixtures.

The Record chain files are generated by tools/record_chain_ref.py from PERD §32.1; this file checks that they are current, that
their chains are real, that v1 was not edited, and that every grant-void reason has a fixture and an unknown one is rejected.
"""
import hashlib
import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import FIXTURES, ROOT, load_schemas, make_registry, validator_for  # noqa: E402

sys.path.insert(0, str(ROOT / "tools"))
import record_chain_ref as ref  # noqa: E402

SCHEMAS = load_schemas()
REGISTRY = make_registry(SCHEMAS)
V2 = SCHEMAS["record-event.v2.json"]
VALID = FIXTURES / "valid" / "record-event.v2"
INVALID = FIXTURES / "invalid" / "record-event.v2"


def events():
    return {p.stem: json.loads(p.read_text()) for p in sorted(VALID.glob("*.json"))}


def check(doc, version="record-event.v2"):
    return list(validator_for(version, SCHEMAS, REGISTRY).iter_errors(doc))


class GrantVoidReasons(unittest.TestCase):
    """PERD §27.1 and REQ-EXE-003 name nine void reasons; v1 listed three. Each has a fixture; an unknown one is rejected."""

    NINE = ["INTENT_SUPERSEDED", "STATE_CHANGED", "POLICY_SUPERSEDED", "SIGNATURE_INVALID", "EXPIRED", "BINDING_MISMATCH", "WRITES_DISABLED",
            "REVALIDATION_UNAVAILABLE", "REJECTED_STALE_VERSION"]
    ADDED = ["SIGNATURE_INVALID", "EXPIRED", "BINDING_MISMATCH", "WRITES_DISABLED", "REVALIDATION_UNAVAILABLE", "REJECTED_STALE_VERSION"]

    def test_v2_lists_exactly_the_nine_and_all_are_distinct(self):
        enum = V2["$defs"]["GrantVoidReason"]["enum"]
        self.assertEqual(sorted(enum), sorted(self.NINE))
        self.assertEqual(len(enum), len(set(enum)))

    def test_v1_is_unchanged_and_still_lists_three(self):
        v1 = SCHEMAS["record-event.v1.json"]["$defs"]["GrantVoidReason"]["enum"]
        self.assertEqual(sorted(v1), ["INTENT_SUPERSEDED", "POLICY_SUPERSEDED", "STATE_CHANGED"])
        for reason in self.ADDED:
            self.assertNotIn(reason, v1, "the six were added in v2, v1 was not edited")

    def test_each_reason_has_a_valid_fixture_that_carries_it(self):
        found = events()
        for reason in self.NINE:
            doc = found.get(f"grant_voided_{reason.lower()}")
            self.assertIsNotNone(doc, f"no fixture for {reason}")
            self.assertEqual((doc["event_type"], doc["reason"]), ("GRANT_VOIDED", reason))
            self.assertEqual(check(doc), [], reason)

    def test_each_reason_is_rejected_when_the_event_is_not_a_void(self):
        for reason in self.NINE:
            doc = dict(events()["intent_admitted" if "intent_admitted" in events() else "genesis_event"])
            doc["reason"] = reason
            self.assertTrue(check(doc), f"{reason} on an event that is not GRANT_VOIDED must be rejected")

    def test_an_unknown_reason_is_rejected(self):
        base = events()["grant_voided_expired"]
        for bad in ["SOMETHING_ELSE", "expired", "Expired", "", " EXPIRED", "TIMEOUT", "SUCCEEDED", "REJECTED_STALE_VERSION_2", None, 7]:
            doc = dict(base, reason=bad)
            self.assertTrue(check(doc), f"reason {bad!r} must be rejected")

    def test_the_six_are_not_valid_v1_reasons(self):
        for reason in self.ADDED:
            doc = {"schema_version": "1.0", "tenant_id": "ten_demo", "correlation_id": "corr_4c21f9", "event_id": "recev_1", "prev_hash": "sha256:" + "0" * 64,
                   "hash": "sha256:" + "1" * 64, "written_by": "EXECUTION", "event_type": "GRANT_VOIDED", "reason": reason, "object_ref": "grt_0001", "at": "2026-10-01T09:48:00Z"}
            self.assertTrue(check(doc, "record-event"), f"{reason} must stay invalid under v1")


class VersionsDoNotMix(unittest.TestCase):
    def test_a_v1_event_is_not_a_v2_event_and_the_reverse(self):
        v1 = json.loads((FIXTURES / "valid" / "record-event" / "genesis_event.json").read_text())
        self.assertFalse(check(v1, "record-event"))
        self.assertTrue(check(v1), "a v1 event must not validate as v2")
        for name, doc in events().items():
            self.assertTrue(check(doc, "record-event"), f"{name} must not validate as v1")

    def test_the_v1_genesis_value_of_64_zeros_is_not_a_v2_prev_hash(self):
        doc = dict(events()["genesis_event"], prev_hash="sha256:" + "0" * 64)
        self.assertTrue(check(doc))

    def test_v1_files_were_not_edited(self):
        """A published major is never edited (AGENT-15): record-event.v1.json and reconstruction.v1.json keep the bytes they had when v2 was added.
        A change to either is a new major in a new file; if this test must change, that is the change to review."""
        pinned = {"record-event.v1.json": "380af4fc6c3e90f4da807259b224e5dfb24a44ad211043313ca7ac44179b7628", "reconstruction.v1.json": "033650683ed44e8e2bc261e8e2951d570341b1682bbf291520acc0e085dd8bba"}
        for name, digest in pinned.items():
            self.assertEqual(hashlib.sha256((ROOT / "contracts" / "schemas" / name).read_bytes()).hexdigest(), digest, f"{name} was edited in place")


class Chains(unittest.TestCase):
    """Every valid v2 fixture is a real link of a real chain: the hashes are computed, not typed."""

    def test_the_first_event_of_a_tenant_chain_carries_the_tenant_scoped_genesis_hash(self):
        for name, doc in events().items():
            self.assertEqual(doc["seq"], 1 if name != "second_event" else 2, name)
            if doc["seq"] == 1:
                self.assertEqual(doc["prev_hash"], ref.genesis_hash(doc["tenant_id"]), name)
                self.assertNotEqual(doc["prev_hash"], "sha256:" + "0" * 64)
        a, b = ref.genesis_hash("ten_demo"), ref.genesis_hash("ten_other")
        self.assertNotEqual(a, b, "the genesis hash is per tenant")
        self.assertEqual(a, "sha256:" + hashlib.sha256(b"noema:genesis:ten_demo").hexdigest())

    def test_every_hash_is_the_hash_of_its_event(self):
        for name, doc in events().items():
            body = {k: v for k, v in doc.items() if k != "hash"}
            self.assertEqual(doc["hash"], ref.event_hash(doc["prev_hash"], body), name)

    def test_the_empty_payload_hash_is_the_hash_of_the_empty_object(self):
        self.assertEqual(ref.EMPTY, "sha256:44136fa355b3678a1146ad16f7e8649e94fb4fc21fe77e8310c060f61caaff8a")
        self.assertEqual(events()["genesis_event"]["payload_hash"], ref.EMPTY)

    def test_reconstruction_v2_fixtures_carry_a_chain_that_links_up(self):
        for path in sorted((FIXTURES / "valid" / "reconstruction.v2").glob("*.json")):
            body = json.loads(path.read_text())
            prev = ref.genesis_hash(body["tenant_id"])
            for i, e in enumerate(body["events"], start=1):
                self.assertEqual((e["seq"], e["prev_hash"], e["schema_version"]), (i, prev, "2.0"), path.name)
                self.assertEqual(e["hash"], ref.event_hash(prev, {k: v for k, v in e.items() if k != "hash"}), path.name)
                prev = e["hash"]
            self.assertEqual(body["chain"]["head_hash"], prev, path.name)


class Reproducible(unittest.TestCase):
    def test_the_generated_files_are_what_the_generator_writes(self):
        stale = [str(p.relative_to(ROOT)) for p, text in ref.outputs().items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        self.assertEqual(stale, [], "run: python3 -I tools/record_chain_ref.py --write")


