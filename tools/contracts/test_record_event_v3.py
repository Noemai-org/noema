"""record-event.v3 and reconstruction.v3 (DEC-2026-10-27-actor-and-payload-hash, PERD v1.17 §32.1): what JSON Schema cannot state,
checked over the fixtures. The chain files are generated by tools/record_chain_ref_v3.py; the payload-hash vectors were produced by an
independent implementation (tools/payload_hash_independent.js) and are only checked here."""
import hashlib
import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import FIXTURES, ROOT, load_schemas, make_registry, validator_for  # noqa: E402

sys.path.insert(0, str(ROOT / "tools"))
import jcs_ref  # noqa: E402
import record_chain_ref_v3 as ref  # noqa: E402

SCHEMAS = load_schemas()
REGISTRY = make_registry(SCHEMAS)
V3 = SCHEMAS["record-event.v3.json"]
VALID = FIXTURES / "valid" / "record-event.v3"

# Typed here from PERD v1.17 §32.1, not read from the schema or the generator.
EMITTERS = ["core-edge", "core-trust", "core-execution", "core-outcome", "core-record", "core-evidence", "core-workflows", "model-service", "benchmark-runner",
            "admin",  # PERD §41.1 identities table
            "mock-ledger", "mock-switch", "mock-destination", "mock-customer", "mock-policy", "mock-case", "mock-clock"]  # PERD §34.1 logical services
KINDS = ["customer", "operator", "approver", "auditor", "regulator", "admin"]


def events():
    return {p.stem: json.loads(p.read_text()) for p in sorted(VALID.glob("*.json"))}


def check(doc, version="record-event.v3"):
    return list(validator_for(version, SCHEMAS, REGISTRY).iter_errors(doc))


def event(**changes):
    return {**events()["genesis_event"], **changes}


class ClosedSets(unittest.TestCase):
    def test_the_emitters_are_the_seventeen_of_perd_41_1_and_34_1(self):
        have = V3["$defs"]["Emitter"]["enum"]
        self.assertEqual(sorted(have), sorted(EMITTERS))
        self.assertEqual(len(have), len(set(have)))

    def test_the_two_benchmark_only_services_are_not_emitters(self):
        for name in ("fault-controller", "fixture-loader"):
            self.assertNotIn(name, V3["$defs"]["Emitter"]["enum"])
            self.assertTrue(check(event(written_by=name, actor=name)), name)

    def test_the_principal_kinds_are_the_six_and_service_is_not_one(self):
        self.assertEqual(sorted(V3["$defs"]["PrincipalKind"]["enum"]), sorted(KINDS))
        self.assertNotIn("service", KINDS)
        self.assertTrue(check(event(actor="service:core-trust")))

    def test_every_emitter_has_a_valid_fixture_and_every_kind_has_one(self):
        found = events()
        for emitter in EMITTERS:
            doc = found[f"emitter_{emitter.replace('-', '_')}"]
            self.assertEqual((doc["written_by"], doc["actor"]), (emitter, emitter))
            self.assertEqual(check(doc), [], emitter)
        for kind in KINDS:
            doc = found[f"principal_{kind}"]
            self.assertEqual(doc["actor"].split(":")[0], kind)
            self.assertEqual(check(doc), [], kind)

    def test_regulator_and_auditor_are_two_kinds(self):
        self.assertEqual(check(event(actor="regulator:usr_9")), [])
        self.assertEqual(check(event(actor="auditor:usr_9")), [])

    def test_an_unknown_emitter_is_rejected(self):
        for bad in ["TRUST", "core-understanding", "Core-Trust", "core_trust", "", " core-trust", "customer", "service", None, 7]:
            self.assertTrue(check(event(written_by=bad, actor="core-trust")), f"written_by {bad!r}")


class Principal(unittest.TestCase):
    def test_actor_is_required(self):
        doc = event()
        del doc["actor"]
        self.assertTrue(check(doc))

    def test_a_person_is_kind_colon_id_and_the_id_never_holds_a_colon(self):
        for ok in ["customer:usr_88213", "approver:usr_synth_014", "operator:a.b-C_9", "admin:" + "a" * 64, "auditor:0"]:
            self.assertEqual(check(event(actor=ok)), [], ok)
        for bad in ["customer:", ":usr_1", "customer:a:b", "customer:-a", "customer:_a", "customer:" + "a" * 65, "customer:usr 1", "customer: usr_1", "Customer:usr_1",
                    "guest:usr_1", "service:core-trust", "customer", "usr_1"]:
            self.assertTrue(check(event(actor=bad)), bad)

    def test_a_system_caused_event_names_the_emitter_as_its_own_principal(self):
        self.assertEqual(check(event(written_by="core-execution", actor="core-execution")), [])
        self.assertTrue(check(event(written_by="core-trust", actor="core-execution")), "another emitter's identity is not this emitter's principal")
        self.assertTrue(check(event(written_by="admin", actor="core-trust")))

    def test_the_control_plane_acting_for_an_administrator(self):
        self.assertEqual(check(event(written_by="admin", actor="admin:usr_admin_01")), [])
        self.assertEqual(check(event(written_by="admin", actor="admin")), [])

    def test_the_v2_forms_are_not_v3_principals(self):
        for old in ["TRUST", "EXECUTION", "EXECUTION:usr_88213"]:
            self.assertTrue(check(event(actor=old)), old)


class VersionsDoNotMix(unittest.TestCase):
    def test_v2_and_v3_events_are_not_each_others(self):
        v2 = json.loads((FIXTURES / "valid" / "record-event.v2" / "genesis_event.json").read_text())
        self.assertEqual(check(v2, "record-event.v2"), [])
        self.assertTrue(check(v2), "a v2 event must not validate as v3")
        for name, doc in events().items():
            self.assertTrue(check(doc, "record-event.v2"), f"{name} must not validate as v2")
            self.assertTrue(check(doc, "record-event"), f"{name} must not validate as v1")

    def test_published_majors_were_not_edited(self):
        """A published major is never edited (AGENT-15): these files keep the bytes they had when the next major was added."""
        pinned = {"record-event.v1.json": "380af4fc6c3e90f4da807259b224e5dfb24a44ad211043313ca7ac44179b7628",
                  "reconstruction.v1.json": "033650683ed44e8e2bc261e8e2951d570341b1682bbf291520acc0e085dd8bba",
                  "record-event.v2.json": "bef23dc84b82f113acee39b0fb0ce25e27dfacd078bb4f60aef427125bf4eff2",
                  "reconstruction.v2.json": "dacc39ec78516d87b5cee8d9199d99b34e95b715ffe4a8d59413a155673b1d7c"}
        for name, digest in pinned.items():
            self.assertEqual(hashlib.sha256((ROOT / "contracts" / "schemas" / name).read_bytes()).hexdigest(), digest, f"{name} was edited in place")

    def test_grant_void_reasons_and_event_types_match_v2(self):
        v2 = SCHEMAS["record-event.v2.json"]["$defs"]
        for key in ("RecordEventType", "SecurityKind", "GrantVoidReason", "ProviderFailoverReason"):
            self.assertEqual(V3["$defs"][key], v2[key], key)


class Chains(unittest.TestCase):
    def test_the_first_event_carries_the_tenant_scoped_genesis_hash_and_every_hash_is_computed(self):
        for name, doc in events().items():
            if doc["seq"] == 1:
                self.assertEqual(doc["prev_hash"], ref.genesis_hash(doc["tenant_id"]), name)
            body = {k: v for k, v in doc.items() if k != "hash"}
            self.assertEqual(doc["hash"], ref.event_hash(doc["prev_hash"], body), name)
            self.assertEqual(doc["schema_version"], "3.0")

    def test_an_event_without_an_object_has_the_hash_of_the_empty_object(self):
        self.assertEqual(events()["genesis_event"]["payload_hash"], "sha256:44136fa355b3678a1146ad16f7e8649e94fb4fc21fe77e8310c060f61caaff8a")

    def test_reconstruction_v3_fixtures_carry_a_chain_that_links_up(self):
        for path in sorted((FIXTURES / "valid" / "reconstruction.v3").glob("*.json")):
            body = json.loads(path.read_text())
            prev = ref.genesis_hash(body["tenant_id"])
            for i, e in enumerate(body["events"], start=1):
                self.assertEqual((e["seq"], e["prev_hash"], e["schema_version"]), (i, prev, "3.0"), path.name)
                self.assertEqual(e["hash"], ref.event_hash(prev, {k: v for k, v in e.items() if k != "hash"}), path.name)
                self.assertIn(e["written_by"], EMITTERS)
                prev = e["hash"]
            self.assertEqual(body["chain"]["head_hash"], prev, path.name)


class PayloadHash(unittest.TestCase):
    """PERD v1.17 §32.1: payload_hash = SHA-256(JCS(payload)), RFC 8785, integers only. The recorded vectors come from an independent implementation."""

    GOLDEN = json.loads((FIXTURES / "golden_vectors.json").read_text(encoding="utf-8"))

    def test_the_four_required_vectors_are_present_and_agree_with_this_implementation(self):
        names = [v["name"] for v in self.GOLDEN["payload_hash_vectors"]]
        self.assertEqual(names, ["empty_object", "nested_object", "unicode_string", "integers"])
        self.assertEqual(ref.check_payload_vectors(self.GOLDEN), [])

    def test_the_input_bytes_are_recorded_beside_each_hash_and_hash_to_it(self):
        for v in self.GOLDEN["payload_hash_vectors"]:
            raw = bytes.fromhex(v["input_bytes_hex"])
            self.assertEqual(raw.decode("utf-8"), v["input_bytes_utf8"], v["name"])
            self.assertEqual("sha256:" + hashlib.sha256(raw).hexdigest(), v["expected_hash"], v["name"])

    def test_members_sort_by_utf16_code_unit_not_by_code_point(self):
        self.assertEqual(jcs_ref.jcs({"￿": 2, "\U0001F600": 1}), '{"\U0001F600":1,"￿":2}')

    def test_negative_zero_is_written_zero(self):
        self.assertEqual(jcs_ref.jcs(json.loads('{"n":-0}')), '{"n":0}')

    def test_a_non_integer_number_or_a_larger_integer_is_rejected(self):
        for v in self.GOLDEN["payload_rejected_vectors"]:
            with self.assertRaises(jcs_ref.NotCanonical, msg=v["name"]):
                jcs_ref.jcs(json.loads(v["payload_json"]))
        self.assertGreaterEqual(len(self.GOLDEN["payload_rejected_vectors"]), 6)


