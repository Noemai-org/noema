"""Generate the Go and Pydantic types of every contract, and the TypeScript types and parsers of the contracts the UI reads (CON-03, REQ-API-001, REQ-UI-001, AGENT-15).

    python3 -I tools/codegen/generate.py --write    regenerate the committed files
    python3 -I tools/codegen/generate.py --check    fail if any committed file differs, is missing, or was added by hand

The generator is Python standard library only; it needs `gofmt` (shipped with the Go toolchain) to format the Go it writes.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import go  # noqa: E402
import ir  # noqa: E402
import py  # noqa: E402
import ts  # noqa: E402

ROOT = HERE.parents[1]
SCHEMA_DIR = "contracts/schemas"
GO_DIR = "services/core/internal/contracts"
PY_DIR = "services/model/noema_model/contracts"
# Not "contracts/": tools/ci/check_image_files.py refuses that path fragment in the ui image (the repository-level contracts directory must not ship in it).
TS_DIR = "ui/src/contract_types"
MARKER = "Code generated by tools/codegen"

# Hand-written files that may sit beside generated ones: documentation, Go tests of the generated package, and intentref.go, the one parser of common.v1#IntentRef
# (ruling A319: "ParseIntentRef next to the generated type"). It is a function, not a contract type.
GO_ALLOWED = {"doc.go", "README.md", "intentref.go"}
PY_ALLOWED = {"README.md"}
TS_ALLOWED = {"README.md"}


def load_schemas(root: Path = ROOT) -> dict[str, dict]:
    out = {}
    for p in sorted((root / SCHEMA_DIR).glob("*.json")):
        out[p.name] = json.loads(p.read_text(encoding="utf-8"))
    if not out:
        raise ir.GenerationError(f"no schemas in {root / SCHEMA_DIR}")
    return out


def is_excluded(file: str, lang: str = "") -> bool:
    """excluded.json names the contract, or a prefix of it, so no service holds its types; with lang="go", also the ones held back from Go."""
    cfg = json.loads((HERE / "excluded.json").read_text(encoding="utf-8"))
    key = file.removesuffix(".json")
    base = key.rsplit(".v", 1)[0]
    if base in cfg["names"] or any(base.startswith(pre) for pre in cfg["prefixes"]):
        return True
    return lang == "go" and key in cfg["go_only"]["names"]


def gofmt(src: str, name: str) -> str:
    try:
        r = subprocess.run(["gofmt"], input=src, capture_output=True, text=True, check=False)
    except FileNotFoundError as e:
        raise ir.GenerationError("gofmt not found: install the Go toolchain (the generated Go is formatted with it)") from e
    if r.returncode != 0:
        raise ir.GenerationError(f"gofmt refused {name}: {r.stderr.strip()[:600]}")
    return r.stdout


def render_all(schemas: dict[str, dict]) -> dict[str, str]:
    """Every generated file by repository-relative path."""
    every = ir.build_schemas(schemas)
    built = {f: b for f, b in every.items() if not is_excluded(f)}
    for f, b in built.items():
        hidden = sorted(r for r in ir.references(b) if is_excluded(r))
        if hidden:
            raise ir.GenerationError(f"{f} refers to {hidden}, which tools/codegen/excluded.json keeps out of the services")
    built_go = {f: b for f, b in built.items() if not is_excluded(f, "go")}
    for f, b in built_go.items():
        hidden = sorted(r for r in ir.references(b) if is_excluded(r, "go"))
        if hidden:
            raise ir.GenerationError(f"{f} refers to {hidden}, which tools/codegen/excluded.json keeps out of the Go types")
    g, p = go.Go(built_go), py.Py(built)
    files: dict[str, str] = {}
    for f, b in built_go.items():
        name = go.file_name(f)
        files[f"{GO_DIR}/{name}"] = gofmt(g.render_schema(b), name)
    for f, b in built.items():
        files[f"{PY_DIR}/{py.module_name(f)}.py"] = p.render_schema(b)
    files[f"{GO_DIR}/runtime_gen.go"] = gofmt(g.render_runtime(), "runtime_gen.go")
    files[f"{GO_DIR}/enum_values_gen.json"] = json.dumps(g.data_values(), indent=1) + "\n"
    files[f"{GO_DIR}/registry_gen.go"] = gofmt(g.render_registry(), "registry_gen.go")
    files[f"{PY_DIR}/_base.py"] = p.render_base()
    files[f"{PY_DIR}/registry.py"] = p.render_registry()
    files[f"{PY_DIR}/__init__.py"] = p.render_init()
    files.update(render_ts(schemas, every))
    return files


def render_ts(schemas: dict[str, dict], every: dict[str, ir.Built]) -> dict[str, str]:
    """The UI's TypeScript: the roots of ts.json and every contract they refer to, each with its parsers, a runtime and one index (entry point) per audience: `customer`, `operator`,
    `benchmark` (the aggregate scorecard view of the benchmark UI, A250; noema#677) and `approver` (the approver's answer body, confirmation-answer.v1; noema#760). The benchmark and approver
    lists are their own: operator.ts holds the customer and operator roots and never the benchmark or the approver one."""
    cfg = json.loads((HERE / "ts.json").read_text(encoding="utf-8"))
    customer, operator, benchmark = list(cfg["customer"]), list(cfg["operator"]), list(cfg.get("benchmark", []))
    approver = list(cfg.get("approver", []))
    roots = customer + [r for r in operator if r not in customer]
    emitted = roots + [r for r in benchmark + approver if r not in roots]
    for r in emitted:
        if r not in every:
            raise ir.GenerationError(f"tools/codegen/ts.json names {r}, which is not a contract")
        if is_excluded(r):
            raise ir.GenerationError(f"tools/codegen/ts.json names {r}, which tools/codegen/excluded.json keeps out of the services")
    needed, todo = set(), list(emitted)
    while todo:
        f = todo.pop()
        if f in needed:
            continue
        needed.add(f)
        todo.extend(ir.references(every[f]))
    hidden = sorted(f for f in needed if is_excluded(f))
    if hidden:
        raise ir.GenerationError(f"ts.json reaches {hidden}, which tools/codegen/excluded.json keeps out of the services")
    t = ts.Ts({f: every[f] for f in sorted(needed)})
    t.keep = t.reachable([every[r].root.name for r in emitted])
    files = {f"{TS_DIR}/{py.module_name(f)}.ts": t.render_schema(every[f]) for f in sorted(needed) if set(every[f].named) & t.keep}
    files[f"{TS_DIR}/_runtime.ts"] = ts.RUNTIME
    files[f"{TS_DIR}/customer.ts"] = t.render_index(customer)
    files[f"{TS_DIR}/operator.ts"] = t.render_index(roots)
    if benchmark:
        files[f"{TS_DIR}/benchmark.ts"] = t.render_index(benchmark)
    if approver:
        files[f"{TS_DIR}/approver.ts"] = t.render_index(approver)
    return files


def check(out_root: Path = ROOT, schemas: dict[str, dict] | None = None) -> list[str]:
    """Problems with the committed output under out_root; empty when it is exactly what the schemas generate."""
    want = render_all(schemas if schemas is not None else load_schemas())
    problems: list[str] = []
    for rel, text in sorted(want.items()):
        path = out_root / rel
        if not path.is_file():
            problems.append(f"missing: {rel} (run: make codegen)")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"differs: {rel} is not what the schemas generate (a generated file was edited by hand, or the schemas changed without make codegen)")
    for d, allowed, suffix in ((GO_DIR, GO_ALLOWED, ".go"), (PY_DIR, PY_ALLOWED, ".py"), (TS_DIR, TS_ALLOWED, ".ts")):
        base = out_root / d
        if not base.is_dir():
            continue
        for path in sorted(base.iterdir()):
            rel = f"{d}/{path.name}"
            if path.name == "__pycache__" or rel in want:
                continue
            if path.is_file() and (path.name in allowed or (suffix == ".go" and path.name.endswith("_test.go"))):
                if path.suffix == suffix and MARKER in path.read_text(encoding="utf-8")[:200]:
                    problems.append(f"unexpected: {rel} claims to be generated and is not")
                continue
            problems.append(f"unexpected: {rel} is not a generated file; contract types are never hand-written (AGENT-15)")
    return problems


def write(out_root: Path = ROOT) -> list[str]:
    want = render_all(load_schemas())
    for rel, text in want.items():
        path = out_root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    removed = []
    for d, suffix in ((GO_DIR, "_gen.go"), (PY_DIR, ".py"), (TS_DIR, ".ts")):
        for path in sorted((out_root / d).glob("*" + suffix)):
            if f"{d}/{path.name}" not in want:
                path.unlink()
                removed.append(f"{d}/{path.name}")
    return removed


def main(argv: list[str]) -> int:
    if len(argv) != 1 or argv[0] not in ("--write", "--check"):
        print(__doc__, file=sys.stderr)
        return 2
    try:
        if argv[0] == "--write":
            removed = write()
            print(f"wrote {len(render_all(load_schemas()))} files" + (f", removed {removed}" if removed else ""))
            return 0
        problems = check()
    except ir.GenerationError as e:
        print(f"codegen FAIL: {e}", file=sys.stderr)
        return 1
    for p in problems:
        print(f"codegen FAIL: {p}", file=sys.stderr)
    if problems:
        return 1
    print("codegen OK: the committed types are exactly what contracts/schemas generate")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
