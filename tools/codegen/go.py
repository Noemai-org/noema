"""Go types for the contracts (CON-03). One file per schema, plus a runtime file and a registry, all `*_gen.go`.

What a generated type guarantees on decode, because a Go struct cannot say it: unknown members are refused where the schema is
closed, required members are present, a member that may not be null is not null, no member is repeated, an enum or constant holds
one of its values. What it leaves to the JSON Schema validator: patterns, bounds, lengths and every conditional rule.
Standard library only.
"""
from __future__ import annotations

import json
import re
from typing import Any

import ir

# Values that the architecture lint (tools/lint/golint/terms.go, benchmarkTerms) keeps out of Go source in the core. An enum value that
# contains one is carried as data in enum_values_gen.json, as record/chain does with actors.json, so the core can refuse or accept it
# without a constant that names it. A test requires the lint to pass over the generated tree.
BANNED = re.compile(r"benchmark|heldout|held_out|oracle|bench_mode", re.I)

HEADER = "// Code generated by tools/codegen from contracts/schemas. DO NOT EDIT.\n\npackage contracts\n"


def file_name(schema_file: str) -> str:
    m = re.match(r"^([a-z0-9-]+)\.v([0-9]+)\.json$", schema_file)
    return f"{m[1].replace('-', '_')}_v{m[2]}_gen.go"


def comment(text: str, name: str, source: str) -> str:
    one = " ".join(text.split())
    if len(one) > 220:
        one = one[:217].rstrip() + "..."
    lines = [f"// {name} is generated from {source}."]
    if one:
        lines.append(f"// {one}")
    return "\n".join(lines) + "\n"


class Go:
    def __init__(self, built: dict[str, ir.Built]):
        self.built = built
        self.all: dict[str, ir.Named] = {n: nm for b in built.values() for n, nm in b.named.items()}

    # -- type questions answered over the finished set ---------------------------------------------------------------
    def follow(self, t: Any, seen: tuple[str, ...] = ()) -> Any:
        while isinstance(t, ir.Ref):
            if t.name in seen:
                raise ir.GenerationError(f"reference cycle through {t.name}")
            seen += (t.name,)
            t = self.all[t.name].type
        return t

    def nullable(self, t: Any) -> bool:
        seen: tuple[str, ...] = ()
        while True:
            if getattr(t, "nullable", False):
                return True
            if not isinstance(t, ir.Ref) or t.name in seen:
                return False
            seen += (t.name,)
            t = self.all[t.name].type

    def is_string(self, t: Any) -> bool:
        t = self.follow(t)
        if isinstance(t, ir.Prim):
            return t.kind == "string"
        if isinstance(t, ir.Enum):
            return all(isinstance(v, str) for v in t.values)
        if isinstance(t, ir.Const):
            return isinstance(t.value, str)
        if isinstance(t, ir.Union):
            return all(self.is_string(a) for a in t.alts)
        return False

    def is_raw(self, t: Any) -> bool:
        """Carried as raw JSON: a member that is any value, the constant null, or a union that is not all strings."""
        t = self.follow(t)
        return (isinstance(t, ir.Prim) and t.kind in ("any", "null")) or (isinstance(t, ir.Const) and t.value is None) or (
            isinstance(t, ir.Union) and not self.is_string(t))

    # -- type expressions ---------------------------------------------------------------------------------------------
    def texpr(self, t: Any) -> str:
        if isinstance(t, ir.Prim):
            return {"string": "string", "integer": "int64", "number": "json.Number", "boolean": "bool", "null": "json.RawMessage", "any": "json.RawMessage"}[t.kind]
        if isinstance(t, ir.Const):
            v = t.value
            return "json.RawMessage" if v is None else "bool" if isinstance(v, bool) else "int64" if isinstance(v, int) else "string"
        if isinstance(t, ir.Ref):
            return t.name
        if isinstance(t, ir.Arr):
            return "[]" + self.elem(t.item)
        if isinstance(t, ir.MapOf):
            return "map[string]" + self.elem(t.value)
        raise ir.GenerationError(f"no Go expression for {type(t).__name__}")

    def elem(self, t: Any) -> str:
        e = self.texpr(t)
        return "*" + e if self.nullable(t) and not self.is_raw(t) else e

    def field_type(self, f: ir.Field_) -> tuple[str, str]:
        """(Go type, tag options). Optional or nullable members are pointers so absence and zero stay distinct; a member that is
        optional and nullable is an Opt, so absent and null stay distinct too."""
        t = self.texpr(f.type)
        nullable = self.nullable(f.type)
        if self.is_raw(f.type):
            return t, "" if f.required else ",omitempty"
        if not f.required and nullable:
            return f"Opt[{t}]", ",omitzero"
        if not f.required:
            return "*" + t, ",omitempty"
        return ("*" + t if nullable else t), ""

    # -- named types --------------------------------------------------------------------------------------------------
    def named(self, nm: ir.Named, source: str) -> str:
        t = nm.type
        n = nm.name
        out = comment(nm.doc, n, f"{source}#{nm.path or ''}".rstrip("#"))
        if isinstance(t, ir.Obj):
            return out + self.struct(n, t)
        if isinstance(t, ir.Enum):
            return out + self.enum(n, t)
        if isinstance(t, ir.Const) and t.value is None:
            return out + self.raw(n, "null", [], False)
        if isinstance(t, ir.Const):
            return out + f"type {n} {self.texpr(t)}\n"
        if isinstance(t, ir.Ref):
            return out + f"type {n} = {t.name}\n"
        if isinstance(t, ir.Arr):
            return out + f"type {n} []{self.elem(t.item)}\n"
        if isinstance(t, ir.MapOf):
            return out + f"type {n} map[string]{self.elem(t.value)}\n"
        if isinstance(t, ir.Union):
            return out + (f"type {n} string\n" if self.is_string(t) else self.raw(n, "one of its alternatives", t.alts, t.nullable))
        if isinstance(t, ir.Prim):
            if t.kind in ("number", "null", "any"):
                return out + f"type {n} = {self.texpr(t)}\n"
            return out + f"type {n} {self.texpr(t)}\n"
        raise ir.GenerationError(f"{n}: no Go declaration for {type(t).__name__}")

    def raw(self, n: str, what: str, alts: list[Any], nullable: bool) -> str:
        """A value carried as raw JSON that is checked on decode: the constant null, or one of several shapes. The bytes are kept as
        they came, so a document is encoded as it was received."""
        out = (f"type {n} json.RawMessage\n\nfunc (u {n}) MarshalJSON() ([]byte, error) {{\n\tif len(u) == 0 {{\n\t\treturn []byte(\"null\"), nil\n\t}}\n"
               f"\treturn []byte(u), nil\n}}\n\nfunc (u *{n}) UnmarshalJSON(b []byte) error {{\n")
        if not alts:
            out += (f"\tif !isNull(b) {{\n\t\treturn fmt.Errorf(\"contracts: {n}: must be null\")\n\t}}\n")
        else:
            out += (f"\tif isNull(b) {{\n" + ("\t\t*u = append((*u)[:0], b...)\n\t\treturn nil\n" if nullable
                    else f"\t\treturn fmt.Errorf(\"contracts: {n}: null is not allowed\")\n") + "\t}\n")
            for i, a in enumerate(alts):
                if isinstance(a, ir.Prim) and a.kind in ("any", "null"):
                    out += "\t*u = append((*u)[:0], b...)\n\treturn nil\n}\n"
                    return out
                t = self.texpr(a)
                if isinstance(a, ir.Ref) and self.is_raw(a):
                    t = a.name
                out += f"\tvar v{i} {t}\n\tif json.Unmarshal(b, &v{i}) == nil {{\n\t\t*u = append((*u)[:0], b...)\n\t\treturn nil\n\t}}\n"
            out += f"\treturn fmt.Errorf(\"contracts: {n}: matches none of its alternatives\")\n}}\n"
            return out
        out += "\t*u = append((*u)[:0], b...)\n\treturn nil\n}\n"
        return out

    def enum(self, n: str, e: ir.Enum) -> str:
        if not all(isinstance(v, str) for v in e.values):
            raise ir.GenerationError(f"{n}: only string enums are modelled")
        names: dict[str, str] = {}
        data = [v for v in e.values if BANNED.search(v)]
        for v in e.values:
            if v in data:
                continue
            c = n + (ir.pascal(v) or "Empty")
            if c in names or c in self.all:
                raise ir.GenerationError(f"{n}: constant name {c} for {v!r} is already taken")
            names[c] = v
        consts = "\n".join(f"\t{c} {n} = {json.dumps(v)}" for c, v in names.items())
        cases = ", ".join(names)
        tail = f"\tif isDataValue({json.dumps(n)}, s) {{\n\t\t*e = {n}(s)\n\t\treturn nil\n\t}}\n" if data else ""
        sw = f"\tswitch v := {n}(s); v {{\n\tcase {cases}:\n\t\t*e = v\n\t\treturn nil\n\t}}\n" if names else ""
        return (f"type {n} string\n\n" + (f"const (\n{consts}\n)\n\n" if names else "") +
                f"func (e *{n}) UnmarshalJSON(b []byte) error {{\n"
                f"\tvar s string\n\tif err := json.Unmarshal(b, &s); err != nil {{\n\t\treturn fmt.Errorf(\"contracts: {n}: %w\", err)\n\t}}\n"
                f"{sw}{tail}"
                f"\treturn fmt.Errorf(\"contracts: {n}: %q is not one of its values\", s)\n}}\n")

    def data_values(self) -> dict[str, list[str]]:
        out: dict[str, list[str]] = {}
        for nm in self.all.values():
            if isinstance(nm.type, ir.Enum):
                vals = sorted(v for v in nm.type.values if BANNED.search(v))
                if vals:
                    out[nm.name] = vals
        return dict(sorted(out.items()))

    def struct(self, n: str, o: ir.Obj) -> str:
        seen: dict[str, str] = {}
        lines, consts, normalise = [], [], []
        for f in o.fields:
            gn = ir.pascal(f.prop)
            if not gn or gn in seen or gn in ("Extra",) and o.extra is not None:
                raise ir.GenerationError(f"{n}: field name {gn!r} for {f.prop!r} collides")
            seen[gn] = f.prop
            gt, opts = self.field_type(f)
            lines.append(f'\t{gn} {gt} `json:"{f.prop}{opts}"`')
            ft = self.follow(f.type)
            if isinstance(f.type, ir.Const):
                consts.append((gn, f, gt))
            if f.required and not self.nullable(f.type) and isinstance(ft, (ir.Arr, ir.MapOf)):
                normalise.append((gn, self.texpr(f.type), "{}"))
        extra_t = None
        if o.extra is not None:
            extra_t = "json.RawMessage" if isinstance(o.extra, ir.Prim) and o.extra.kind == "any" else self.elem(o.extra)
            lines.append(f'\tExtra map[string]{extra_t} `json:"-"`')
        body = "\n".join(lines)
        props = ", ".join(f'"{f.prop}": true' for f in o.fields)
        required = ", ".join(json.dumps(f.prop) for f in o.fields if f.required)
        nonnull = ", ".join(f'"{f.prop}": true' for f in o.fields if not self.nullable(f.type) and not self.is_raw(f.type))
        shape = (f"var {n}Shape = objectShape{{name: {json.dumps(n)}, props: map[string]bool{{{props}}}, required: []string{{{required}}}, "
                 f"nonNull: map[string]bool{{{nonnull}}}, closed: {'true' if o.extra is None else 'false'}}}")
        out = f"type {n} struct {{\n{body}\n}}\n\n{shape}\n\n"
        out += f"func (t *{n}) UnmarshalJSON(b []byte) error {{\n\traw, err := {n}Shape.check(b)\n\tif err != nil {{\n\t\treturn err\n\t}}\n"
        out += f"\ttype alias {n}\n\tvar a alias\n\tif err := json.Unmarshal(b, &a); err != nil {{\n\t\treturn fmt.Errorf(\"contracts: {n}: %w\", err)\n\t}}\n"
        for gn, f, gt in consts:
            lit = json.dumps(f.type.value) if not isinstance(f.type.value, bool) else ("true" if f.type.value else "false")
            if f.type.value is None:
                out += f"\tif len(a.{gn}) > 0 && string(a.{gn}) != \"null\" {{\n\t\treturn fmt.Errorf(\"contracts: {n}.{f.prop}: must be null\")\n\t}}\n"
            elif gt.startswith("*"):
                out += f"\tif a.{gn} != nil && *a.{gn} != {lit} {{\n\t\treturn fmt.Errorf(\"contracts: {n}.{f.prop}: must be %s\", {json.dumps(lit)})\n\t}}\n"
            elif gt.startswith("Opt["):
                out += f"\tif a.{gn}.Set && !a.{gn}.Null && a.{gn}.Value != {lit} {{\n\t\treturn fmt.Errorf(\"contracts: {n}.{f.prop}: must be %s\", {json.dumps(lit)})\n\t}}\n"
            else:
                out += f"\tif a.{gn} != {lit} {{\n\t\treturn fmt.Errorf(\"contracts: {n}.{f.prop}: must be %s\", {json.dumps(lit)})\n\t}}\n"
        if extra_t:
            out += ("\ta.Extra = map[string]" + extra_t + "{}\n\tfor k, v := range raw {\n\t\tif " + n + "Shape.props[k] {\n\t\t\tcontinue\n\t\t}\n"
                    "\t\tvar x " + extra_t + "\n\t\tif err := json.Unmarshal(v, &x); err != nil {\n"
                    "\t\t\treturn fmt.Errorf(\"contracts: " + n + ".%s: %w\", k, err)\n\t\t}\n\t\ta.Extra[k] = x\n\t}\n")
        else:
            out += "\t_ = raw\n"
        out += f"\t*t = {n}(a)\n\treturn nil\n}}\n"
        if normalise or extra_t:
            out += f"\nfunc (t {n}) MarshalJSON() ([]byte, error) {{\n\ttype alias {n}\n\ta := alias(t)\n"
            for gn, ty, empty in normalise:
                out += f"\tif a.{gn} == nil {{\n\t\ta.{gn} = {ty}{empty}\n\t}}\n"
            if extra_t:
                out += ("\tb, err := json.Marshal(a)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n"
                        "\tvar m map[string]json.RawMessage\n\tif err := json.Unmarshal(b, &m); err != nil {\n\t\treturn nil, err\n\t}\n"
                        "\tfor k, v := range t.Extra {\n\t\tx, err := json.Marshal(v)\n\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tm[k] = x\n\t}\n"
                        "\treturn json.Marshal(m)\n}\n")
            else:
                out += "\treturn json.Marshal(a)\n}\n"
        return out

    # -- files ---------------------------------------------------------------------------------------------------------
    def render_schema(self, b: ir.Built) -> str:
        body = "\n".join(self.named(nm, b.file) for nm in b.named.values())
        return HEADER + '\nimport (\n\t"encoding/json"\n\t"fmt"\n)\n\n' + body

    def render_runtime(self) -> str:
        return HEADER + RUNTIME

    def render_registry(self) -> str:
        rows = []
        for f in sorted(self.built):
            key = f[: -len(".json")]
            b = self.built[f]
            rows.append(f'\t"{key}": func() any {{ return new({b.root.name}) }},')
            for name, nm in b.named.items():
                if nm.path.startswith("$defs/"):
                    rows.append(f'\t"{key}#{nm.path[len("$defs/"):]}": func() any {{ return new({name}) }},')
        return HEADER + ("\n// Types maps `<schema>` (for example \"record-event.v3\") and `<schema>#<definition>` to a constructor of the generated type.\n"
                         "// It lets a contract test decode a fixture by name. The schema validator, not this table, decides what is valid.\n"
                         "var Types = map[string]func() any{\n" + "\n".join(rows) + "\n}\n")


