#!/usr/bin/env python3
"""Generates tests/vectors.sql for the SEC-12 pgsodium spike. SYNTHETIC test keys only (AGENT-25).

Standard library only: Ed25519 is the RFC 8032 section 6 reference algorithm. The script checks its own output
against RFC 8032 section 7.1 TEST 1 and TEST 2 before writing anything. It is run by hand when the vectors change;
CI does not run it, it runs the committed output. Usage: python3 -I gen_vectors.py > tests/vectors.sql
"""
import hashlib
import sys

P = 2**255 - 19
Q = 2**252 + 27742317777372353535851937790883648493
D = -121665 * pow(121666, P - 2, P) % P
SQRT_M1 = pow(2, (P - 1) // 4, P)


def _recover_x(y, sign):
    if y >= P:
        return None
    x2 = (y * y - 1) * pow(D * y * y + 1, P - 2, P) % P
    if x2 == 0:
        return None if sign else 0
    x = pow(x2, (P + 3) // 8, P)
    if (x * x - x2) % P != 0:
        x = x * SQRT_M1 % P
    if (x * x - x2) % P != 0:
        return None
    return P - x if (x & 1) != sign else x


_GY = 4 * pow(5, P - 2, P) % P
_G = (_recover_x(_GY, 0), _GY, 1, _recover_x(_GY, 0) * _GY % P)


def _add(a, b):
    a1, b1 = (a[1] - a[0]) * (b[1] - b[0]) % P, (a[1] + a[0]) * (b[1] + b[0]) % P
    c1, d1 = 2 * a[3] * b[3] * D % P, 2 * a[2] * b[2] % P
    e, f, g, h = b1 - a1, d1 - c1, d1 + c1, b1 + a1
    return (e * f % P, g * h % P, f * g % P, e * h % P)


def _mul(s, pt):
    r = (0, 1, 1, 0)
    while s > 0:
        if s & 1:
            r = _add(r, pt)
        pt = _add(pt, pt)
        s >>= 1
    return r


def _enc(pt):
    zi = pow(pt[2], P - 2, P)
    x, y = pt[0] * zi % P, pt[1] * zi % P
    return int.to_bytes(y | ((x & 1) << 255), 32, "little")


def _h(m):
    return int.from_bytes(hashlib.sha512(m).digest(), "little")


def _expand(seed):
    h = hashlib.sha512(seed).digest()
    a = int.from_bytes(h[:32], "little")
    a &= (1 << 254) - 8
    a |= 1 << 254
    return a, h[32:]


def public_key(seed):
    return _enc(_mul(_expand(seed)[0], _G))


def sign(seed, msg):
    a, prefix = _expand(seed)
    pk = _enc(_mul(a, _G))
    r = _h(prefix + msg) % Q
    rs = _enc(_mul(r, _G))
    s = (r + _h(rs + pk + msg) * a) % Q
    return rs + int.to_bytes(s, 32, "little")


def self_check():
    seed1 = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
    assert public_key(seed1).hex() == "d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a"
    assert sign(seed1, b"").hex() == (
        "e5564300c360ac729086e2cc806e828a84877f1eb8e5d974d873e065224901555fb8821590a33bacc61e39701cf9b46bd25bf5f0595bbe24655141438e7a100b")
    seed2 = bytes.fromhex("4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb")
    assert public_key(seed2).hex() == "3d4017c3e843895a92b70aa74d1b7ebc9c982ccf2ec4968cc0cd55f12af4660c"
    assert sign(seed2, bytes.fromhex("72")).hex() == (
        "92a009a9f0d4cab8720e820b5f642540a2b27b5416503f8fb3762223ebdb69da085ac1e43e15996e458f3613d0f11d8c387b2eaeb4302aeeb00d291612bb0c00")


def key(name):
    return hashlib.sha256(b"SYNTHETIC spike key " + name.encode()).digest()


def receipt_message(tenant, grant, attempt, state, key_id):
    # Spike-only byte layout. The real canonical bytes (JCS) are the W1 design (GOV-28), not this.
    return f"v0|{tenant}|{grant}|{attempt}|{state}|{key_id}".encode()


def lit(b):
    return "'\\x" + b.hex() + "'"


def main():
    self_check()
    out = ["-- GENERATED by gen_vectors.py. Do not edit by hand. SYNTHETIC test keys and data only (AGENT-25).",
           "CREATE TABLE spike_vec (name text PRIMARY KEY, msg bytea NOT NULL, sig bytea NOT NULL, pk bytea NOT NULL,",
           "  expect boolean NOT NULL, why text NOT NULL);"]
    rows = []
    seed1 = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
    pk1, sig1 = public_key(seed1), sign(seed1, b"")
    seed2 = bytes.fromhex("4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb")
    pk2, sig2 = public_key(seed2), sign(seed2, bytes.fromhex("72"))
    rows.append(("rfc8032_test1", b"", sig1, pk1, True, "RFC 8032 7.1 TEST 1"))
    rows.append(("rfc8032_test2", bytes.fromhex("72"), sig2, pk2, True, "RFC 8032 7.1 TEST 2"))
    for i in (0, 31, 32, 63):
        bad = bytearray(sig1)
        bad[i] ^= 1
        rows.append((f"flip_sig_byte_{i}", b"", bytes(bad), pk1, False, "one flipped bit in the signature"))
    rows.append(("flip_msg", b"\x00", sig1, pk1, False, "message differs from the signed one"))
    badpk = bytearray(pk1)
    badpk[0] ^= 1
    rows.append(("flip_pk", b"", sig1, bytes(badpk), False, "one flipped bit in the public key"))
    rows.append(("wrong_key", b"", sig1, pk2, False, "valid signature under a different key"))
    s = int.from_bytes(sig1[32:], "little")
    assert s < Q and s + Q < 2**253  # passes the weak 'S < 2^253' check of pg_ed25519, fails a canonical check
    rows.append(("malleable_s_plus_l", b"", sig1[:32] + int.to_bytes(s + Q, 32, "little"), pk1, False,
                 "S + L: same point, non-canonical S"))
    identity = int.to_bytes(1, 32, "little")
    rows.append(("small_order_key_and_r", b"anything", identity + bytes(32), identity, False,
                 "identity public key with R = identity and S = 0 verifies for any message in a lax verifier"))
    p_plus_1 = int.to_bytes(P + 1, 32, "little")
    rows.append(("noncanonical_identity_key", b"anything", identity + bytes(32), p_plus_1, False,
                 "identity encoded as y = p + 1"))
    rows.append(("small_order_r_valid_key", b"", identity + sig1[32:], pk1, False, "R of small order with a real key"))
    rows.append(("all_zero_signature", b"", bytes(64), pk1, False, "all-zero signature"))
    for name, msg, sig, pk, expect, why in rows:
        out.append(f"INSERT INTO spike_vec VALUES ('{name}', {lit(msg)}, {lit(sig)}, {lit(pk)}, {str(expect).lower()}, '{why}');")

    keys = {k: key(k) for k in ("A", "B", "C", "D")}
    out.append("CREATE TABLE spike_key (key_id text PRIMARY KEY, public_key bytea NOT NULL, valid_from timestamptz NOT NULL,")
    out.append("  valid_to timestamptz, revoked_at timestamptz);")
    spec = {"kA": ("A", "2020-01-01", None, None), "kB": ("B", "2020-01-01", None, "2025-01-01"),
            "kC": ("C", "2099-01-01", None, None), "kD": ("D", "2020-01-01", "2021-01-01", None)}
    for kid, (name, vf, vt, rv) in spec.items():
        vt_s = f"'{vt}'" if vt else "NULL"
        rv_s = f"'{rv}'" if rv else "NULL"
        out.append(f"INSERT INTO spike_key VALUES ('{kid}', {lit(public_key(keys[name]))}, '{vf}', {vt_s}, {rv_s});")
    out.append("CREATE TABLE spike_receipt_sig (name text PRIMARY KEY, tenant_id text, grant_id text, attempt int, state text,")
    out.append("  key_id text, signature bytea);")

    def rec(name, tenant, grant, attempt, state, key_id, signer):
        msg = receipt_message(tenant, grant, attempt, state, key_id)
        sig = sign(keys[signer], msg)
        out.append(f"INSERT INTO spike_receipt_sig VALUES ('{name}', '{tenant}', '{grant}', {attempt}, '{state}', '{key_id}', {lit(sig)});")
        return sig

    st = "REJECTED_STALE_VERSION"
    ok = rec("ok", "t1", "g1", 1, st, "kA", "A")
    out.append(f"INSERT INTO spike_receipt_sig VALUES ('replay_grant', 't1', 'g2', 1, '{st}', 'kA', {lit(ok)});")
    out.append(f"INSERT INTO spike_receipt_sig VALUES ('replay_tenant', 't2', 'g1', 1, '{st}', 'kA', {lit(ok)});")
    out.append(f"INSERT INTO spike_receipt_sig VALUES ('replay_attempt', 't1', 'g1', 2, '{st}', 'kA', {lit(ok)});")
    out.append(f"INSERT INTO spike_receipt_sig VALUES ('replay_state', 't1', 'g1', 1, 'APPLIED', 'kA', {lit(ok)});")
    rec("revoked_key", "t1", "g3", 1, st, "kB", "B")
    rec("not_yet_valid_key", "t1", "g4", 1, st, "kC", "C")
    rec("expired_key", "t1", "g5", 1, st, "kD", "D")
    rec("unknown_key", "t1", "g6", 1, st, "kZ", "A")
    rec("signed_by_other_key", "t1", "g7", 1, st, "kA", "B")
    forged = hashlib.sha512(b"SYNTHETIC forged signature").digest()
    out.append(f"INSERT INTO spike_receipt_sig VALUES ('forged_well_formed', 't1', 'g8', 1, '{st}', 'kA', {lit(forged)});")
    out.append(f"INSERT INTO spike_receipt_sig VALUES ('forged_shape_only', 't1', 'g9', 1, '{st}', 'kA', {lit(bytes.fromhex('ab' * 64))});")
    rec("ok_second", "t1", "g10", 1, st, "kA", "A")
    rec("ok_third", "t1", "g11", 1, st, "kA", "A")
    sys.stdout.write("\n".join(out) + "\n")


main()
